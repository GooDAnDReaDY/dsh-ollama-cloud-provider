/**
 * Regenerate `src/models.generated.ts` from the live Ollama Cloud catalog and
 * models.dev prices. The live endpoint is the source of truth for context,
 * reasoning levels, modalities and visibility; models.dev supplies per-token
 * prices and output limits, which the live catalog does not expose.
 *
 *   npm run sync:models
 */
import { writeFile } from 'node:fs/promises'
import path from 'node:path'

const LIVE = 'https://ollama.com/v1/models'
const PRICES = 'https://models.dev/api.json'
const PROVIDER = 'ollama-cloud'
const OUTPUT = path.resolve('src/models.generated.ts')

/** Published off-peak rates, USD per 1M tokens. */
const OFF_PEAK = {
  'deepseek-v4-pro:0813': [0.66, 1.98, 0.022],
  'deepseek-v4.1-flash': [0.15, 0.60, 0.003],
  'deepseek-v4.1-flash:1017': [0.15, 0.60, 0.003],
}

/**
 * Standard rates for models where models.dev already stores the off-peak
 * figure. Taken from the published ollama.com/pricing table.
 */
const STANDARD = {
  'deepseek-v4-pro:0813': [1.32, 3.96, 0.044],
  'deepseek-v4.1-flash': [0.30, 1.20, 0.006],
  'deepseek-v4.1-flash:1017': [0.30, 1.20, 0.006],
}

const liveResponse = await fetch(LIVE, { headers: { 'user-agent': 'dsh-ollama-cloud-provider-sync/0.1.0' } })
if (!liveResponse.ok) throw new Error(`${LIVE} returned ${liveResponse.status}`)
const livePayload = await liveResponse.json()
const live = Array.isArray(livePayload.models) ? livePayload.models : []
if (live.length === 0) throw new Error('the live catalog returned no models')

let prices = {}
try {
  const priceResponse = await fetch(PRICES)
  if (priceResponse.ok) {
    const catalog = await priceResponse.json()
    prices = catalog[PROVIDER]?.models ?? {}
  }
} catch {
  prices = {}
}

function costOf(id, model) {
  const raw = model?.cost ?? {}
  const base = STANDARD[id]
    ?? [Number(raw.input) || 0, Number(raw.output) || 0, Number(raw.cache_read) || 0]
  const offPeak = OFF_PEAK[id]
  return {
    input: base[0],
    output: base[1],
    cacheRead: base[2],
    ...(offPeak === undefined
      ? {}
      : { offPeakInput: offPeak[0], offPeakOutput: offPeak[1], offPeakCacheRead: offPeak[2] }),
  }
}

const models = new Map()

for (const entry of live) {
  const id = String(entry.slug ?? '')
  if (id === '') continue
  const price = prices[id] ?? prices[id.replace(/:\d+$/, '')] ?? {}
  const levels = Array.isArray(entry.supported_reasoning_levels)
    ? entry.supported_reasoning_levels.map((level) => String(level.effort ?? '')).filter(Boolean)
    : []
  const modalities = Array.isArray(entry.input_modalities) ? entry.input_modalities : []
  const cost = costOf(id, price)
  models.set(id, {
    id,
    name: String(entry.display_name ?? id),
    transport: 'native',
    contextWindow: Number(entry.context_window) || Number(entry.max_context_window) || 131072,
    maxTokens: Number(price.limit?.output) || 32768,
    input: modalities.includes('image') ? ['text', 'image'] : ['text'],
    reasoning: levels,
    reasoningToggle: levels.length === 0 && price.reasoning === true,
    tools: price.tool_call !== false,
    free: id === 'beam' || id.endsWith('-free'),
    available: entry.supported_in_api !== false && entry.visibility !== 'hide',
    ...(typeof entry.default_reasoning_level === 'string'
      ? { defaultReasoning: entry.default_reasoning_level }
      : {}),
    cost,
  })
}

const ordered = Object.fromEntries([...models.entries()].sort(([a], [b]) => a.localeCompare(b)))

const body = `// Generated by scripts/sync-models.mjs from ${LIVE} and ${PRICES}.
// Do not edit by hand.

export type OllamaCloudTransport = 'native' | 'openai-chat'

export interface ModelCost {
  readonly input: number
  readonly output: number
  readonly cacheRead: number
  readonly offPeakInput?: number
  readonly offPeakOutput?: number
  readonly offPeakCacheRead?: number
}

export interface OllamaCloudModelMeta {
  readonly id: string
  readonly name: string
  readonly transport: OllamaCloudTransport
  readonly contextWindow: number
  readonly maxTokens: number
  readonly input: readonly ('text' | 'image')[]
  readonly reasoning: readonly string[]
  readonly reasoningToggle: boolean
  readonly tools: boolean
  readonly free: boolean
  readonly available: boolean
  readonly defaultReasoning?: string
  readonly cost: ModelCost
}

export const GENERATED_MODELS: Record<string, OllamaCloudModelMeta> = ${JSON.stringify(ordered, null, 2)}
`

await writeFile(OUTPUT, body, 'utf8')
console.log(`wrote ${Object.keys(ordered).length} models to ${OUTPUT}`)
